export function translate(language, key, values = {}) {
  const message = translations[language]?.[key] || translations.en[key] || (
    language === 'en' ? key : screenTranslations[key]?.[{ si: 0, ta: 1 }[language]] || key
  );
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{{${name}}}`, String(value)),
    message,
  );
}

export function translateText(language, text) {
  const trimmed = text.trim();
  if (!trimmed) return text;

  const existingKey = Object.keys(translations.en).find((key) => translations.en[key] === trimmed);
  if (existingKey) {
    const translated = translations[language]?.[existingKey];
    if (translated) return `${text.slice(0, text.indexOf(trimmed))}${translated}${text.slice(text.indexOf(trimmed) + trimmed.length)}`;
  }

  const translation = screenTranslations[trimmed]?.[{ si: 0, ta: 1 }[language]];
  if (!translation) return text;
  return `${text.slice(0, text.indexOf(trimmed))}${translation}${text.slice(text.indexOf(trimmed) + trimmed.length)}`;
}
